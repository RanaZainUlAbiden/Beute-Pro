type CopyKeys<T, Prefix extends string = ''> = {
  [K in keyof T & string]: T[K] extends CopyPair
    ? K extends '$' ? Prefix : `${Prefix}${Prefix extends '' ? '' : '.'}${K}`
    : CopyKeys<T[K], `${Prefix}${Prefix extends '' ? '' : '.'}${K}`>
}[keyof T & string];

export type TranslationKey = CopyKeys<typeof copy>;

function language(index: 0 | 1): Record<TranslationKey, string> {
  const result: Record<string, string> = {};
  const visit = (branch: CopyTree, prefix = ''): void => {
    for (const [name, value] of Object.entries(branch)) {
      const key = name === '$' ? prefix : (prefix ? prefix + '.' : '') + name;
      if (Array.isArray(value)) result[key] = value[index];
      else visit(value as CopyTree, key);
    }
  };
  visit(copy);
  return result as Record<TranslationKey, string>;
}

